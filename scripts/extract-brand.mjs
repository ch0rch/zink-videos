// Splits the official ZinkERP lockup (zinkerp.com/brand) into the pieces the film animates:
// the symbol's diamond modules as data, and the untouched wordmark outlines as their own SVG.
import {readFileSync, writeFileSync} from 'node:fs';

const source = readFileSync('public/brand/zinkerp-horizontal_dark_tight.svg', 'utf8');
const viewBox = source.match(/viewBox="([^"]+)"/)[1];
const paths = [...source.matchAll(/<path fill="([^"]+)" d="([^"]+)"\/>/g)].map(([, fill, d]) => ({fill, d}));

const diamond = /^M([\d.]+) ([\d.]+)L([\d.]+) ([\d.]+)L([\d.]+) ([\d.]+)L([\d.]+) ([\d.]+)Z$/;
const modules = [];
const wordmark = [];
for (const path of paths) {
	const match = path.d.match(diamond);
	if (!match) {
		wordmark.push(path);
		continue;
	}
	const [topX, topY, , , , bottomY] = match.slice(1).map(Number);
	modules.push({cx: topX, cy: (topY + bottomY) / 2, r: (bottomY - topY) / 2, fill: path.fill});
}
if (modules.length !== 16 || wordmark.length !== 2) {
	throw new Error(`Unexpected lockup structure: ${modules.length} modules, ${wordmark.length} wordmark paths`);
}

writeFileSync(
	'public/brand/zinkerp-wordmark-dark.svg',
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${wordmark
		.map((path) => `<path fill="${path.fill}" d="${path.d}"/>`)
		.join('')}</svg>\n`,
);

const [, , width, height] = viewBox.split(' ').map(Number);
writeFileSync(
	'src/showreel/brand/symbol.ts',
	`// Generated by scripts/extract-brand.mjs from public/brand/zinkerp-horizontal_dark_tight.svg.
// Units are the lockup's own viewBox; every module is a square standing on a corner.
export const LOCKUP = {width: ${width}, height: ${height}, symbolWidth: 80} as const;

export type SymbolModule = {cx: number; cy: number; r: number; fill: string};

export const SYMBOL_MODULES: readonly SymbolModule[] = ${JSON.stringify(modules, null, '\t')};
`,
);
console.log(`modules: ${modules.length}, wordmark paths: ${wordmark.length}, viewBox: ${viewBox}`);
